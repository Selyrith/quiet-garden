/**
 * Мобильная шкала интерфейса.
 *
 * Источник значений — исследования, а не вкус:
 *  • Apple HIG: минимальный тач-таргет 44×44 pt.
 *  • Material Design 3: 48×48 dp (≈9 мм) для большинства платформ.
 *  • NN/G (Parhi, Karlson & Bederson, MobileHCI '06): минимум 1×1 см
 *    физического размера, иначе растёт время промаха и «rage taps».
 *  • web.dev / WCAG 2.5.8: между соседними таргетами ≥8 px, иначе
 *    палец задевает соседнюю кнопку.
 *
 * Поэтому: тач-таргет 48, зазор 12, а визуальная кнопка может быть
 * меньше тач-зоны — это нормально и рекомендуется.
 */
export const MOBILE = {
  /** Минимальная сторона тач-таргета (Dawnfield: 56dp — выше Apple HIG 44pt и Material 48dp). */
  tap: 56,
  /** Комфортный тач-таргет для основных действий. */
  tapComfortable: 56,
  /** Зазор между соседними интерактивными элементами (web.dev: ≥8). */
  gap: 12,
  /** Отступ от края экрана. */
  edge: 16,
  /** Высота основной кнопки. */
  buttonH: 52,
  /** Высота кнопки в плотном списке. */
  buttonHSmall: 44,
  /** Радиус кнопок и панелей. */
  radius: 16,
  radiusPanel: 24,
  /** Нижняя «безопасная» зона под жест-бар. */
  safeBottom: 34,

  /** Типографика: минимум для читаемого текста на телефоне. */
  font: {
    caption: 12,
    body: 15,
    label: 16,
    title: 20,
    display: 26,
  },

  /**
   * Контраст. Значения подобраны так, чтобы текст на панели давал
   * ≥4.5:1 (WCAG AA) — при «слипании» это главный рычаг.
   */
  ink: {
    strong: '#3d2e20',
    body: '#3d2e20',
    muted: '#8a7a66',
    inverse: '#fcf8f0',
  },
};

/**
 * Подогнать размер кнопки под мобильные нормы.
 * Возвращает размеры, которые НЕ меньше тач-таргета, но и не раздуваются
 * на весь экран (претензия «всё стало большим»).
 */
export function fitTapTarget(w, h) {
  return {
    w: Math.max(w, MOBILE.tap),
    h: Math.max(h, MOBILE.buttonHSmall),
  };
}