export function generateLore(seed, rarity) {
  const rng = mulberry32(seed * 31 + 2000);
  const opener = OPENERS[Math.floor(rng() * OPENERS.length)];
  const trait  = TRAITS[Math.floor(rng() * TRAITS.length)];
  const ending = ENDINGS[Math.floor(rng() * ENDINGS.length)];
  const habitat = HABITATS[Math.floor(rng() * HABITATS.length)];
  const legend  = LEGENDS[Math.floor(rng() * LEGENDS.length)];
  const rarityNote = RARITY_NOTES[rarity?.id] || '';
  return {
    description: `${opener} ${trait}. ${ending}`,
    habitat,
    legend,
    rarityNote
  };
}
