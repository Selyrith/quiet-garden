export const PET_COUNT = PETS.length;

export function getRandomPet(rng = Math.random) {
  const idx = Math.floor(rng() * PETS.length);
  return { ...PETS[idx] };
}

export function getPetById(id) {
  return PETS.find(p => p.id === id) || PETS[0];
}

